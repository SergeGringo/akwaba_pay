<script>

   var scrollToTopBtn = document.getElementById("scrollToTopBtn");
   var lastScrollTop = 0; // Variable pour stocker la position de défilement précédente

   window.onscroll = function () {
      var currentScrollTop = document.documentElement.scrollTop || document.body.scrollTop;

      // Vérifie si l'utilisateur défile vers le haut
      if (currentScrollTop < lastScrollTop) {
         // Si l'utilisateur défile vers le haut, afficher le bouton
         scrollToTopBtn.style.display = "block";
      } else {
         // Si l'utilisateur défile vers le bas, cacher le bouton
         scrollToTopBtn.style.display = "none";
      }

      // Vérifie si l'utilisateur est en haut de la page
      if (currentScrollTop === 0) {
         scrollToTopBtn.style.display = "none"; // Cacher le bouton si on est en haut
      }

      // Met à jour la position de défilement précédente
      lastScrollTop = currentScrollTop <= 0 ? 0 : currentScrollTop; // Pour éviter les valeurs négatives
   };

   // Faire défiler vers le haut lorsque le bouton est cliqué
   scrollToTopBtn.onclick = function () {
      window.scrollTo({ top: 0, behavior: 'smooth' }); // Défilement en douceur vers le haut
   };

</script>





