document.addEventListener("DOMContentLoaded", function () {
  const over1 = document.getElementById("over1");
  const over2 = document.getElementById("over2");
  const over3 = document.getElementById("over3");
  const divlist1 = document.querySelector(".list1");
  const divlist2 = document.querySelector(".list2");
  const divlist3 = document.querySelector(".list3");
  const divsecondmenu = document.querySelector(".second_menu_foot");

  // afficher la div list1, 2 et 3 au survol

  over1.addEventListener("mouseenter", function () {
    divlist1.style.display = "block";
    divlist2.style.display = "none"; // Cacher l'autre div
    divlist3.style.display = "none"; // Cacher l'autre div
  });

  over2.addEventListener("mouseenter", function () {
    divlist1.style.display = "none";
    divlist2.style.display = "block"; // Cacher l'autre div
    divlist3.style.display = "none"; // Cacher l'autre div
  });

  over3.addEventListener("mouseenter", function () {
    divlist1.style.display = "none";
    divlist2.style.display = "none"; // Cacher l'autre div
    divlist3.style.display = "block"; // Cacher l'autre div
  });

  // CACHER LA DIV L'ORSQUE LE CURSEUR QUITTE LE OVER

  over1.addEventListener("mouseenter", function () {
    divlist1.style.display = "block";
    divlist2.style.display = "none"; // Cacher l'autre div
    divlist3.style.display = "none"; // Cacher l'autre div
  });

  over1.addEventListener("mouseleave", function () {
    if (!divlist1.matches(":hover")) {
      divlist1.style.display = "none";
    }
  });
  over2.addEventListener("mouseleave", function () {
    if (!divlist2.matches(":hover")) {
      divlist2.style.display = "none";
    }
  });

  over3.addEventListener("mouseleave", function () {
    if (!divlist3.matches(":hover")) {
      divlist3.style.display = "none";
    }
  });

  // GARDER LA DIV VISIBLE TANT QUE LE CURSEUR EST DANS DIV
  divlist1.addEventListener("mouseleave", function () {
    divlist1.style.display = "none";

    divlist2.addEventListener("mouseleave", function () {
      divlist2.style.display = "none";

      divlist3.addEventListener("mouseleave", function () {
        divlist3.style.display = "none";
      });
    });
  });
});

