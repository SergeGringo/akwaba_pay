document.addEventListener("DOMContentLoaded", function () {
  const link1 = document.getElementById("link1");
  const link2 = document.getElementById("link2");
  const divSepts = document.querySelector(".septs");
  const divAstre = document.querySelector(".astre");

  // Afficher la div "septs" au survol du premier lien
  link1.addEventListener("mouseenter", function () {
    divSepts.style.display = "block";
    divAstre.style.display = "none"; // Cacher l'autre div
  });

  // Afficher la div "astre" au survol du deuxième lien
  link2.addEventListener("mouseenter", function () {
    divAstre.style.display = "block";
    divSepts.style.display = "none"; // Cacher l'autre div
  });

  // Cacher les divs lorsque le curseur quitte les liens
  link1.addEventListener("mouseenter", function () {
    divSepts.style.display = "block";
    divAstre.style.display = "none"; // Cacher l'autre div
  });

  link2.addEventListener("mouseleave", function () {
    if (!divAstre.matches(":hover")) {
      divAstre.style.display = "none";
    }
  });

  // Garder la div visible tant que le curseur est sur la div
  divSepts.addEventListener("mouseleave", function () {
    divSepts.style.display = "none";
  });

  divAstre.addEventListener("mouseleave", function () {
    divAstre.style.display = "none";
  });
});

